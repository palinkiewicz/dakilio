#!/usr/bin/env python3
"""Fetch the curated Material Symbols Rounded (outline + filled) used by Dakilio.

Reads tools/icons.txt, writes Android vector drawables into core/designsystem's res/drawable
(sym_<name>.xml and sym_<name>_fill.xml) and generates the typed Kotlin catalog DakilioSymbols.kt.
Material Symbols are Apache-2.0 licensed (https://github.com/google/material-design-icons).

Usage: python3 -I tools/fetch-icons.py
"""
import concurrent.futures
import pathlib
import re
import sys
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIST = ROOT / "tools" / "icons.txt"
RES = ROOT / "core/designsystem/src/main/res/drawable"
KT = ROOT / "core/designsystem/src/main/kotlin/pl/dakil/dakilio/core/designsystem/icon/DakilioSymbols.kt"
URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android/{n}/materialsymbolsrounded/{f}"


def fetch(name: str, filled: bool) -> str | None:
    file = f"{name}_fill1_24px.xml" if filled else f"{name}_24px.xml"
    try:
        with urllib.request.urlopen(URL.format(n=name, f=file), timeout=30) as response:
            return response.read().decode("utf-8")
    except urllib.error.HTTPError:
        return None


def clean(xml: str) -> str:
    # Tint comes from Compose's LocalContentColor; a theme-attr tint only gets in the way.
    return re.sub(r'\s*android:tint="[^"]*"', "", xml)


def camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def main() -> int:
    entries = []
    for line in LIST.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        category, name = line.split()
        if name not in (e[1] for e in entries):
            entries.append((category, name))

    RES.mkdir(parents=True, exist_ok=True)
    for old in RES.glob("sym_*.xml"):
        old.unlink()

    def download(entry):
        _, name = entry
        return entry, fetch(name, filled=False), fetch(name, filled=True)

    available = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=16) as pool:
        for (category, name), outline, filled in pool.map(download, entries):
            if outline is None:
                print(f"missing: {name}", file=sys.stderr)
                continue
            (RES / f"sym_{name}.xml").write_text(clean(outline))
            (RES / f"sym_{name}_fill.xml").write_text(clean(filled or outline))
            available.append((category, name))

    categories = []
    for category, _ in available:
        if category not in categories:
            categories.append(category)

    lines = [
        "// Generated by tools/fetch-icons.py from tools/icons.txt. Do not edit by hand.",
        "package pl.dakil.dakilio.core.designsystem.icon",
        "",
        "import pl.dakil.dakilio.core.designsystem.R",
        "",
        "object DakilioSymbols {",
    ]
    for category, name in available:
        cat = camel(category)
        lines.append(
            f'    val {camel(name)} = VectorSymbol("{name}", R.drawable.sym_{name}, '
            f"R.drawable.sym_{name}_fill, SymbolCategory.{cat})"
        )
    lines += [
        "",
        "    val all: List<VectorSymbol> = listOf(",
        *[f"        {camel(name)}," for _, name in available],
        "    )",
        "}",
        "",
    ]
    KT.parent.mkdir(parents=True, exist_ok=True)
    KT.write_text("\n".join(lines))
    print(f"{len(available)} symbols, categories: {', '.join(categories)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
